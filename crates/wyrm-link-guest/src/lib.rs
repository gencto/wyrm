//! Guest side of the portable link API (ADR 0023): runs an [`App`] inside a WebAssembly component
//! of world `wyrm:app/app` (`crates/wyrm-wasm-host/wit/app/app.wit`).
//!
//! An app crate builds as a `cdylib` for `wasm32-unknown-unknown` and names its app once:
//!
//! ```ignore
//! wyrm_link_guest::export!(MyApp);
//! ```
//!
//! The macro exports the world's functions. They decode the CBOR arguments with `wyrm-core`, call
//! the app and encode its answer. [`GuestHost`] implements [`Host`] over the `wyrm:app/host`
//! imports. Errors cross the boundary as CBOR `{status, msg}` ([`AppError::to_cbor`]). The core
//! module carries the world's component type in a custom section, so `wit-component` can make it a
//! component without the WIT files.

#![deny(unsafe_code)]

// The generated bindings name this crate by its path, also from inside it.
extern crate self as wyrm_link_guest;

/// Bindings generated by `wit-bindgen` for world `wyrm:app/app`. Used by [`export!`]; not an API.
#[doc(hidden)]
#[allow(unsafe_code, clippy::all, missing_docs)]
pub mod bindings {
    wit_bindgen::generate!({
        path: "../wyrm-wasm-host/wit/app",
        world: "wyrm:app/app",
        pub_export_macro: true,
        export_macro_name: "export",
        default_bindings_module: "wyrm_link_guest::bindings",
        runtime_path: "wyrm_link_guest::__rt",
    });
}

#[doc(hidden)]
pub use wit_bindgen::rt as __rt;

use bindings::wyrm::app::host as imports;
use std::cell::RefCell;
use std::thread::LocalKey;
use wyrm_core::{codec, ActionMeta, NodeMeta, Sample, Status, Value};
use wyrm_link_api::{App, AppError, ConnId, Host, Level, ReqId, SubId, TimerId, Who};

/// Exports `$app` (a type that implements [`App`]) as the component's world `wyrm:app/app`.
///
/// Use it once, in the app crate built as a `cdylib`. The app instance lives in a thread-local
/// cell: a component instance runs one call at a time on one thread.
#[macro_export]
macro_rules! export {
    ($app:ty) => {
        const _: () = {
            ::std::thread_local! {
                static __WYRM_APP: ::core::cell::RefCell<::core::option::Option<$app>> =
                    const { ::core::cell::RefCell::new(::core::option::Option::None) };
            }

            struct __WyrmGuest;

            impl $crate::bindings::Guest for __WyrmGuest {
                fn start(
                    config: ::std::vec::Vec<u8>,
                ) -> ::core::result::Result<(), ::std::vec::Vec<u8>> {
                    $crate::__private::start::<$app>(&__WYRM_APP, &config)
                }
                fn on_set(
                    path: ::std::string::String,
                    value: ::std::vec::Vec<u8>,
                    who: ::std::vec::Vec<u8>,
                ) -> ::core::result::Result<(), ::std::vec::Vec<u8>> {
                    $crate::__private::on_set::<$app>(&__WYRM_APP, &path, &value, &who)
                }
                fn on_invoke(
                    path: ::std::string::String,
                    action: ::std::string::String,
                    args: ::std::vec::Vec<u8>,
                    who: ::std::vec::Vec<u8>,
                ) -> ::core::result::Result<::std::vec::Vec<u8>, ::std::vec::Vec<u8>> {
                    $crate::__private::on_invoke::<$app>(&__WYRM_APP, &path, &action, &args, &who)
                }
                fn on_timer(id: u64) {
                    $crate::__private::on_timer::<$app>(&__WYRM_APP, id)
                }
                fn on_value(sub: u64, key: ::std::string::String, sample: ::std::vec::Vec<u8>) {
                    $crate::__private::on_value::<$app>(&__WYRM_APP, sub, &key, &sample)
                }
                fn on_reply(
                    req: u64,
                    result: ::core::result::Result<::std::vec::Vec<u8>, ::std::vec::Vec<u8>>,
                ) {
                    $crate::__private::on_reply::<$app>(&__WYRM_APP, req, result)
                }
                fn stop() {
                    $crate::__private::stop::<$app>(&__WYRM_APP)
                }
            }

    $crate::bindings::export!(__WyrmGuest with_types_in $crate::bindings);
        };
    };
}

/// [`Host`] over the `wyrm:app/host` imports of the component.
#[derive(Debug, Default)]
pub struct GuestHost;

impl GuestHost {
    fn encode_or_log<T: minicbor::Encode<()>>(&mut self, what: &str, v: &T) -> Option<Vec<u8>> {
        match codec::to_vec(v) {
            Ok(b) => Some(b),
            Err(e) => {
                self.log(Level::Error, &format!("{what}: {e}"));
                None
            }
        }
    }
}

fn encode_value(v: &Value) -> Result<Vec<u8>, AppError> {
    codec::to_vec(v).map_err(|e| AppError::new(Status::InternalError, e.to_string()))
}

impl Host for GuestHost {
    fn declare_node(&mut self, path: &str, meta: NodeMeta) {
        if let Some(b) = self.encode_or_log("declare_node", &meta) {
            imports::declare_node(path, &b);
        }
    }

    fn declare_action(&mut self, path: &str, name: &str, action: ActionMeta) {
        if let Some(b) = self.encode_or_log("declare_action", &action) {
            imports::declare_action(path, name, &b);
        }
    }

    fn remove_node(&mut self, path: &str) {
        imports::remove_node(path);
    }

    fn update(&mut self, path: &str, sample: Sample) {
        if let Some(b) = self.encode_or_log("update", &sample) {
            imports::update(path, &b);
        }
    }

    fn now_us(&self) -> u64 {
        imports::now_us()
    }

    fn set_timer(&mut self, after_ms: u64) -> Result<TimerId, AppError> {
        imports::set_timer(after_ms)
            .map(TimerId)
            .map_err(|e| AppError::from_cbor(&e))
    }

    fn cancel_timer(&mut self, t: TimerId) {
        imports::cancel_timer(t.0);
    }

    fn store_get(&self, key: &str) -> Option<Vec<u8>> {
        imports::store_get(key)
    }

    fn store_put(&mut self, key: &str, value: &[u8]) -> Result<(), AppError> {
        imports::store_put(key, value).map_err(|e| AppError::from_cbor(&e))
    }

    fn store_delete(&mut self, key: &str) {
        imports::store_delete(key);
    }

    fn subscribe(&mut self, key: &str) -> Result<SubId, AppError> {
        imports::subscribe(key)
            .map(SubId)
            .map_err(|e| AppError::from_cbor(&e))
    }

    fn unsubscribe(&mut self, sub: SubId) {
        imports::unsubscribe(sub.0);
    }

    fn set(&mut self, key: &str, value: Value) -> Result<ReqId, AppError> {
        let b = encode_value(&value)?;
        imports::set(key, &b)
            .map(ReqId)
            .map_err(|e| AppError::from_cbor(&e))
    }

    fn invoke(&mut self, key: &str, action: &str, args: Value) -> Result<ReqId, AppError> {
        let b = encode_value(&args)?;
        imports::invoke(key, action, &b)
            .map(ReqId)
            .map_err(|e| AppError::from_cbor(&e))
    }

    fn tcp_connect(&mut self, addr: &str, port: u16, timeout_ms: u32) -> Result<ConnId, AppError> {
        imports::tcp_connect(addr, port, timeout_ms)
            .map(ConnId)
            .map_err(|e| AppError::from_cbor(&e))
    }

    fn tcp_send(&mut self, c: ConnId, data: &[u8]) -> Result<(), AppError> {
        imports::tcp_send(c.0, data).map_err(|e| AppError::from_cbor(&e))
    }

    fn tcp_recv(&mut self, c: ConnId, max: u32, timeout_ms: u32) -> Result<Vec<u8>, AppError> {
        imports::tcp_recv(c.0, max, timeout_ms).map_err(|e| AppError::from_cbor(&e))
    }

    fn tcp_close(&mut self, c: ConnId) {
        imports::tcp_close(c.0);
    }

    fn log(&mut self, level: Level, msg: &str) {
        imports::log(level.code(), msg);
    }
}

/// The cell that holds the app instance between calls.
pub type Slot<A> = LocalKey<RefCell<Option<A>>>;

/// The bodies of the exported functions, generic over the app and the host. Used by [`export!`].
#[doc(hidden)]
pub mod __private {
    use super::*;

    pub fn start<A: App>(slot: &'static Slot<A>, config: &[u8]) -> Result<(), Vec<u8>> {
        run_start(slot, &mut GuestHost, config).map_err(|e| e.to_cbor())
    }

    pub fn on_set<A: App>(
        slot: &'static Slot<A>,
        path: &str,
        value: &[u8],
        who: &[u8],
    ) -> Result<(), Vec<u8>> {
        run_on_set(slot, &mut GuestHost, path, value, who).map_err(|e| e.to_cbor())
    }

    pub fn on_invoke<A: App>(
        slot: &'static Slot<A>,
        path: &str,
        action: &str,
        args: &[u8],
        who: &[u8],
    ) -> Result<Vec<u8>, Vec<u8>> {
        run_on_invoke(slot, &mut GuestHost, path, action, args, who).map_err(|e| e.to_cbor())
    }

    pub fn on_timer<A: App>(slot: &'static Slot<A>, id: u64) {
        with_app(slot, |app| app.on_timer(&mut GuestHost, TimerId(id)));
    }

    pub fn on_value<A: App>(slot: &'static Slot<A>, sub: u64, key: &str, sample: &[u8]) {
        run_on_value(slot, &mut GuestHost, sub, key, sample);
    }

    pub fn on_reply<A: App>(slot: &'static Slot<A>, req: u64, result: Result<Vec<u8>, Vec<u8>>) {
        run_on_reply(slot, &mut GuestHost, req, result);
    }

    pub fn stop<A: App>(slot: &'static Slot<A>) {
        run_stop(slot, &mut GuestHost);
    }
}

fn invalid(what: &str, e: impl core::fmt::Display) -> AppError {
    AppError::new(Status::InvalidMessage, format!("{what}: {e}"))
}

/// A caller whose CBOR does not decode has no subject and no grants (fail closed).
fn who_or_nobody(who: &[u8]) -> Who {
    Who::from_cbor(who).unwrap_or_default()
}

fn not_started() -> AppError {
    AppError::new(Status::Busy, "app not started")
}

/// Runs `f` on the app; `None` when it is not started (or stopped).
fn with_app<A: App, R>(slot: &'static Slot<A>, f: impl FnOnce(&mut A) -> R) -> Option<R> {
    slot.with(|cell| cell.borrow_mut().as_mut().map(f))
}

fn run_start<A: App>(
    slot: &'static Slot<A>,
    host: &mut dyn Host,
    config: &[u8],
) -> Result<(), AppError> {
    if slot.with(|cell| cell.borrow().is_some()) {
        return Err(AppError::new(Status::InternalError, "app already started"));
    }
    let config: Value = codec::from_slice(config).map_err(|e| invalid("config", e))?;
    let app = A::start(host, config)?;
    slot.with(|cell| *cell.borrow_mut() = Some(app));
    Ok(())
}

fn run_on_set<A: App>(
    slot: &'static Slot<A>,
    host: &mut dyn Host,
    path: &str,
    value: &[u8],
    who: &[u8],
) -> Result<(), AppError> {
    let value: Value = codec::from_slice(value).map_err(|e| invalid("value", e))?;
    let who = who_or_nobody(who);
    with_app(slot, |app| app.on_set(host, path, value, &who)).unwrap_or_else(|| Err(not_started()))
}

fn run_on_invoke<A: App>(
    slot: &'static Slot<A>,
    host: &mut dyn Host,
    path: &str,
    action: &str,
    args: &[u8],
    who: &[u8],
) -> Result<Vec<u8>, AppError> {
    let args: Value = codec::from_slice(args).map_err(|e| invalid("args", e))?;
    let who = who_or_nobody(who);
    let out = with_app(slot, |app| app.on_invoke(host, path, action, args, &who))
        .unwrap_or_else(|| Err(not_started()))?;
    encode_value(&out)
}

fn run_on_value<A: App>(
    slot: &'static Slot<A>,
    host: &mut dyn Host,
    sub: u64,
    key: &str,
    sample: &[u8],
) {
    match codec::from_slice::<Sample>(sample) {
        Ok(sample) => {
            with_app(slot, |app| app.on_value(host, SubId(sub), key, sample));
        }
        Err(e) => host.log(Level::Warn, &format!("value of {key} dropped: {e}")),
    }
}

fn run_on_reply<A: App>(
    slot: &'static Slot<A>,
    host: &mut dyn Host,
    req: u64,
    result: Result<Vec<u8>, Vec<u8>>,
) {
    let result = match result {
        Ok(b) => codec::from_slice::<Value>(&b).map_err(|e| invalid("reply", e)),
        Err(e) => Err(AppError::from_cbor(&e)),
    };
    with_app(slot, |app| app.on_reply(host, ReqId(req), result));
}

fn run_stop<A: App>(slot: &'static Slot<A>, host: &mut dyn Host) {
    if let Some(mut app) = slot.with(|cell| cell.borrow_mut().take()) {
        app.stop(host);
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use wyrm_core::{Perm, Quality};

    /// Records what the app saw; implements only what the tests reach.
    #[derive(Default)]
    struct Fake {
        logs: Vec<(Level, String)>,
    }

    impl Host for Fake {
        fn declare_node(&mut self, _: &str, _: NodeMeta) {}
        fn declare_action(&mut self, _: &str, _: &str, _: ActionMeta) {}
        fn remove_node(&mut self, _: &str) {}
        fn update(&mut self, _: &str, _: Sample) {}
        fn now_us(&self) -> u64 {
            0
        }
        fn set_timer(&mut self, _: u64) -> Result<TimerId, AppError> {
            Ok(TimerId(1))
        }
        fn cancel_timer(&mut self, _: TimerId) {}
        fn store_get(&self, _: &str) -> Option<Vec<u8>> {
            None
        }
        fn store_put(&mut self, _: &str, _: &[u8]) -> Result<(), AppError> {
            Ok(())
        }
        fn store_delete(&mut self, _: &str) {}
        fn subscribe(&mut self, _: &str) -> Result<SubId, AppError> {
            Ok(SubId(1))
        }
        fn unsubscribe(&mut self, _: SubId) {}
        fn set(&mut self, _: &str, _: Value) -> Result<ReqId, AppError> {
            Ok(ReqId(1))
        }
        fn invoke(&mut self, _: &str, _: &str, _: Value) -> Result<ReqId, AppError> {
            Ok(ReqId(1))
        }
        fn tcp_connect(&mut self, _: &str, _: u16, _: u32) -> Result<ConnId, AppError> {
            Ok(ConnId(1))
        }
        fn tcp_send(&mut self, _: ConnId, _: &[u8]) -> Result<(), AppError> {
            Ok(())
        }
        fn tcp_recv(&mut self, _: ConnId, _: u32, _: u32) -> Result<Vec<u8>, AppError> {
            Ok(Vec::new())
        }
        fn tcp_close(&mut self, _: ConnId) {}
        fn log(&mut self, level: Level, msg: &str) {
            self.logs.push((level, msg.to_owned()));
        }
    }

    /// Keeps every event it gets, to compare with what was sent.
    #[derive(Default)]
    struct Probe {
        config: Option<Value>,
        who: Option<Who>,
        values: Vec<(u64, String, Sample)>,
        replies: Vec<(u64, Result<Value, AppError>)>,
    }

    thread_local! {
        static SEEN: RefCell<Vec<String>> = const { RefCell::new(Vec::new()) };
    }

    impl App for Probe {
        const NAME: &'static str = "probe";
        const VERSION: &'static str = "0.0.0";

        fn start(_: &mut dyn Host, config: Value) -> Result<Self, AppError> {
            if config == Value::Str("fail".into()) {
                return Err(AppError::new(Status::InvalidParameter, "fail"));
            }
            Ok(Probe {
                config: Some(config),
                ..Probe::default()
            })
        }

        fn on_set(
            &mut self,
            _: &mut dyn Host,
            _: &str,
            _: Value,
            who: &Who,
        ) -> Result<(), AppError> {
            self.who = Some(who.clone());
            Ok(())
        }

        fn on_invoke(
            &mut self,
            _: &mut dyn Host,
            _: &str,
            action: &str,
            args: Value,
            who: &Who,
        ) -> Result<Value, AppError> {
            self.who = Some(who.clone());
            match action {
                "echo" => Ok(args),
                _ => Err(AppError::new(Status::NotFound, action)),
            }
        }

        fn on_value(&mut self, _: &mut dyn Host, sub: SubId, key: &str, sample: Sample) {
            self.values.push((sub.0, key.to_owned(), sample));
        }

        fn on_reply(&mut self, _: &mut dyn Host, req: ReqId, result: Result<Value, AppError>) {
            self.replies.push((req.0, result));
        }

        fn stop(&mut self, _: &mut dyn Host) {
            SEEN.with(|s| s.borrow_mut().push("stop".into()));
        }
    }

    fn cbor(v: &Value) -> Vec<u8> {
        codec::to_vec(v).unwrap()
    }

    fn probe<R>(slot: &'static Slot<Probe>, f: impl FnOnce(&Probe) -> R) -> R {
        slot.with(|c| f(c.borrow().as_ref().expect("started")))
    }

    #[test]
    fn start_decodes_config_and_refuses_bad_cbor() {
        thread_local!(static S: RefCell<Option<Probe>> = const { RefCell::new(None) });
        let mut h = Fake::default();
        let e = run_start(&S, &mut h, &[0xff]).unwrap_err();
        assert_eq!(e.status, Status::InvalidMessage);
        let e = run_start(&S, &mut h, &cbor(&Value::Str("fail".into()))).unwrap_err();
        assert_eq!(e.status, Status::InvalidParameter);
        run_start(&S, &mut h, &cbor(&Value::UInt(7))).unwrap();
        assert_eq!(probe(&S, |p| p.config.clone()), Some(Value::UInt(7)));
        let e = run_start(&S, &mut h, &cbor(&Value::Null)).unwrap_err();
        assert_eq!(e.status, Status::InternalError);
    }

    #[test]
    fn calls_before_start_are_busy() {
        thread_local!(static S: RefCell<Option<Probe>> = const { RefCell::new(None) });
        let mut h = Fake::default();
        let e = run_on_set(&S, &mut h, "p", &cbor(&Value::Null), &[]).unwrap_err();
        assert_eq!(e.status, Status::Busy);
        let e = run_on_invoke(&S, &mut h, "p", "echo", &cbor(&Value::Null), &[]).unwrap_err();
        assert_eq!(e.status, Status::Busy);
        run_on_reply(&S, &mut h, 1, Ok(cbor(&Value::Null)));
        run_stop(&S, &mut h);
    }

    #[test]
    fn who_decodes_and_a_bad_who_has_no_grants() {
        thread_local!(static S: RefCell<Option<Probe>> = const { RefCell::new(None) });
        let mut h = Fake::default();
        run_start(&S, &mut h, &cbor(&Value::Null)).unwrap();
        let who = Who {
            subject: Some("user:ann".into()),
            grants: vec![("wy/s/**".into(), Perm::Write)],
        };
        run_on_set(&S, &mut h, "p", &cbor(&Value::Bool(true)), &who.to_cbor()).unwrap();
        assert_eq!(probe(&S, |p| p.who.clone()), Some(who));
        run_on_set(&S, &mut h, "p", &cbor(&Value::Bool(true)), &[0xff]).unwrap();
        assert_eq!(probe(&S, |p| p.who.clone()), Some(Who::default()));
        let e = run_on_set(&S, &mut h, "p", &[0xff], &[]).unwrap_err();
        assert_eq!(e.status, Status::InvalidMessage);
    }

    #[test]
    fn invoke_encodes_the_answer_and_the_error() {
        thread_local!(static S: RefCell<Option<Probe>> = const { RefCell::new(None) });
        let mut h = Fake::default();
        run_start(&S, &mut h, &cbor(&Value::Null)).unwrap();
        let out = run_on_invoke(&S, &mut h, "p", "echo", &cbor(&Value::Int(-3)), &[]).unwrap();
        assert_eq!(codec::from_slice::<Value>(&out).unwrap(), Value::Int(-3));
        let e = run_on_invoke(&S, &mut h, "p", "nope", &cbor(&Value::Null), &[]).unwrap_err();
        assert_eq!(e, AppError::new(Status::NotFound, "nope"));
        let e = run_on_invoke(&S, &mut h, "p", "echo", &[0xff], &[]).unwrap_err();
        assert_eq!(e.status, Status::InvalidMessage);
    }

    #[test]
    fn values_and_replies_decode() {
        thread_local!(static S: RefCell<Option<Probe>> = const { RefCell::new(None) });
        let mut h = Fake::default();
        run_start(&S, &mut h, &cbor(&Value::Null)).unwrap();
        let s = Sample {
            v: Value::Float(1.5),
            q: Quality::Good,
            t: 42,
        };
        run_on_value(&S, &mut h, 3, "wy/s/x", &codec::to_vec(&s).unwrap());
        run_on_value(&S, &mut h, 3, "wy/s/x", &[0xff]);
        assert_eq!(
            probe(&S, |p| p.values.clone()),
            vec![(3, "wy/s/x".to_owned(), s)]
        );
        assert_eq!(h.logs.len(), 1);
        assert_eq!(h.logs[0].0, Level::Warn);

        let denied = AppError::new(Status::PermissionDenied, "no grant");
        run_on_reply(&S, &mut h, 1, Ok(cbor(&Value::UInt(1))));
        run_on_reply(&S, &mut h, 2, Err(denied.to_cbor()));
        run_on_reply(&S, &mut h, 3, Ok(vec![0xff]));
        let replies = probe(&S, |p| p.replies.clone());
        assert_eq!(replies[0], (1, Ok(Value::UInt(1))));
        assert_eq!(replies[1], (2, Err(denied)));
        assert_eq!(
            replies[2].1.as_ref().unwrap_err().status,
            Status::InvalidMessage
        );
    }

    #[test]
    fn stop_calls_the_app_once_and_drops_it() {
        thread_local!(static S: RefCell<Option<Probe>> = const { RefCell::new(None) });
        let mut h = Fake::default();
        run_start(&S, &mut h, &cbor(&Value::Null)).unwrap();
        run_stop(&S, &mut h);
        run_stop(&S, &mut h);
        assert_eq!(SEEN.with(|s| s.borrow().clone()), vec!["stop".to_owned()]);
        assert!(S.with(|c| c.borrow().is_none()));
        let e = run_on_set(&S, &mut h, "p", &cbor(&Value::Null), &[]).unwrap_err();
        assert_eq!(e.status, Status::Busy);
    }
}
