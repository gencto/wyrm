"""Render the WYRM Studio app icon for every platform of studio/app.

    cd studio && python3 tool/app_icon/build.py [night|ember|signal]

Needs: Python 3.10+, numpy, Pillow, and rsvg-convert (macOS: brew install librsvg;
Debian/Ubuntu: apt install librsvg2-bin). The mark and palettes are in icon.py,
the compositing (float background, no banding) in compose.py. Design: the
AppIcon board of the Studio canvas, studio/docs/design/specs/app-icon.md.
"""
import json, os, sys
from PIL import Image
sys.path.insert(0, os.path.dirname(__file__))
from compose import macos, ios, rounded, maskable, android_fg, android_bg, android_mono

VARIANT = sys.argv[1] if len(sys.argv) > 1 else 'night'
APP = os.path.join(os.path.dirname(__file__), '..', '..', 'app')
DOCS = os.path.join(os.path.dirname(__file__), '..', '..', 'docs', 'design', 'icon')

def save(im, *parts):
    path = os.path.join(APP, *parts)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    im.save(path, optimize=True)

# macOS: Apple grid (824 tile, shadow in the margin); 16 and 32 use the three-node mark.
for px in (16, 32, 64, 128, 256, 512, 1024):
    save(macos(VARIANT, px), 'macos/Runner/Assets.xcassets/AppIcon.appiconset', f'app_icon_{px}.png')

# iOS: full bleed, opaque, the system masks it; every slot of Contents.json.
ios_dir = 'ios/Runner/Assets.xcassets/AppIcon.appiconset'
with open(os.path.join(APP, ios_dir, 'Contents.json')) as f:
    for img in json.load(f)['images']:
        pt = float(img['size'].split('x')[0]); px = round(pt * int(img['scale'][0]))
        save(ios(VARIANT, px), ios_dir, img['filename'])

# Android: adaptive icon (API 26+) with foreground, background and themed monochrome layers,
# plus the legacy square for older launchers.
dens = {'mdpi': 1, 'hdpi': 1.5, 'xhdpi': 2, 'xxhdpi': 3, 'xxxhdpi': 4}
res = 'android/app/src/main/res'
for d, k in dens.items():
    save(rounded(VARIANT, round(48 * k), margin=40), res, f'mipmap-{d}', 'ic_launcher.png')
    for name, fn in (('foreground', android_fg), ('background', android_bg), ('monochrome', android_mono)):
        save(fn(VARIANT, round(108 * k)), res, f'mipmap-{d}', f'ic_launcher_{name}.png')
adaptive = '''<?xml version="1.0" encoding="utf-8"?>
<!-- WYRM Studio launcher icon, generated by studio/tool/app_icon/build.py. -->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@mipmap/ic_launcher_background" />
    <foreground android:drawable="@mipmap/ic_launcher_foreground" />
    <monochrome android:drawable="@mipmap/ic_launcher_monochrome" />
</adaptive-icon>
'''
p = os.path.join(APP, res, 'mipmap-anydpi-v26', 'ic_launcher.xml')
os.makedirs(os.path.dirname(p), exist_ok=True)
open(p, 'w').write(adaptive)

# Windows: one .ico with hand-made small sizes (three nodes at 32 and below).
sizes = (16, 20, 24, 32, 40, 48, 64, 256)
imgs = [rounded(VARIANT, s, margin=0 if s <= 32 else 24) for s in sizes]
path = os.path.join(APP, 'windows/runner/resources/app_icon.ico')
imgs[-1].save(path, format='ICO', sizes=[(s, s) for s in sizes], append_images=imgs[:-1])

# Web: favicon, install icons, maskable icons (mark inside the 80 % circle).
save(rounded(VARIANT, 16), 'web/favicon.png')
for px in (192, 512):
    save(rounded(VARIANT, px, margin=32), 'web/icons', f'Icon-{px}.png')
    save(maskable(VARIANT, px), 'web/icons', f'Icon-maskable-{px}.png')

# Linux: a 512 px icon beside the runner (used by the .desktop entry when packaged).
save(rounded(VARIANT, 512, margin=32), 'linux/runner/resources/app_icon.png')

# Masters for the design docs.
os.makedirs(DOCS, exist_ok=True)
for name, im in (('macos-1024', macos(VARIANT, 1024)), ('ios-1024', ios(VARIANT, 1024)), ('rounded-1024', rounded(VARIANT, 1024)),
                 ('android-foreground-432', android_fg(VARIANT, 432)), ('android-monochrome-432', android_mono(VARIANT, 432))):
    im.save(os.path.join(DOCS, f'{VARIANT}-{name}.png'), optimize=True)
print('app icon:', VARIANT)
